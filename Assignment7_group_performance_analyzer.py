# დავალება 7: სტუდენტების ქულების დინამიური ანალიზატორი (Lists, while, try-except, Built-in Functions)
# აღწერა: ფაილში სახელად - 'group_performance_analyzer.py'

# შექმენი პროგრამა, რომელიც საშუალებას აძლევს მასწავლებელს შეიყვანოს კლასის სტუდენტების ქულები.

# <<<<<<<<<<<<<<ძირითადი მოთხოვნები:>>>>>>>>>>>>>>>>>>>>>

# <<<<<<<<<<<<<<შექმენი ცარიელი სია scores = [].>>>>>>>>>>>>>>>>>>>>>
scores = []
# <<<<<<<<<<<<<<გამოიყენე while True ციკლი, სადაც მასწავლებელს მოსთხოვ ქულების შეყვანას.>>>>>>>>>>>>>>>>>>>>>
while True:
    score = input("დასათვლელად შეიყვანეთ სტუდენტის ქულა (დათვლის დასასრულებლად დაწერეთ სიტყვა stop): \n")
# <<<<<<<<<<<<<<თუ მომხმარებელი ჩაწერს სიტყვას "stop", ციკლი უნდა შეწყდეს (break).
    if score.lower() == "stop":
        break
# <<<<<<<<<<<<<<გამოიყენე try-except ბლოკი: თუ შეყვანილი მნიშვნელობა არ არის რიცხვი (და არც "stop"), პროგრამა არ უნდა გაჩერდეს, >>>>>>>>>>>>>>>>>>>>>
# <<<<<<<<<<<<<<არამედ დაბეჭდოს გაფრთხილება ("გთხოვთ შეიყვანოთ სწორი რიცხვი ან 'stop'").>>>>>>>>>>>>>>>>>>>>>
    try:
        score = float(score)
    except ValueError:
        print("გთხოვთ შეიყვანოთ სწორი რიცხვი ან სიტყვა'stop'")
# <<<<<<<<<<<<<<შეამოწმე შემოტანილი რიცხვები და იმ შემთხვევაში თუ რიცხვები მოთავსებულია 0სა და 10ს შორის, ჩაყარე scores ლისტში.>>>>>>>>>>>>>>>>>>>>>
    else:
        if 0 <= score <= 10:
            scores.append(score)
        else:
            print("ქულა უნდა იყოს 0-დან 10-ის დიაპაზონში")

# <<<<<<<<<<<<<<ციკლის დასრულების შემდეგ (როცა მომხმარებელი დაასრულებს შეყვანას): იპოვე ქულებს შორის მინიმალური, მაქსიმალური, >>>>>>>>>>>>>>>>>>>>>
# <<<<<<<<<<<<<<და მათი საშუალო არითმეტიკული(კლასის საშუალო პერფორმანსი)>>>>>>>>>>>>>>>>>>>>>
if len(scores) > 0:
    total = sum(scores)
    minimum = min(scores)
    maximum = max(scores)
    average = total / len(scores)

# <<<<<<<<<<<<<<გამოიტანე ეს მონაცემები ლამაზად ფორმატირებული სტრინგის მეშვეობით>>>>>>>>>>>>>>>>>>>>>
    print("<<< კლასის სტატისტიკა >>>\n")
    print(f"ქულების ჯამი: {total:.2f}")
    print(f"სტუდენტების რაოდენობა: {len(scores)}")
    print(f"მინიმალური ქულა: {minimum:.2f}")
    print(f"მაქსიმალური ქულა: {maximum:.2f}")
    print(f"საშუალო ქულა: {average:.2f}")
# <<<<<<<<<<<<<<ამის შემდეგ ხაზზე  გამოიტანე ყველა მიღებული ქულა ზრდადობით
    print("<<< ქულები ზრდადობით .>>\n")
    print(sorted(scores))
# <<<<<<<<<<<<<<შემდეგ ხაზზე გამოიტანე თუ თითო ქულა რამდენჯერ გამეორდა.>>>>>>>>>>>>>>>>>>>>>
    print("<<< ქულების გამეორება >>>\n")
    for score in sorted(set(scores)):
        print(f"{score} ქულა განმეორდა {scores.count(score)}-ჯერ")
else:
    print("ვალიდური ქულები არ შეგიყვანიათ!")