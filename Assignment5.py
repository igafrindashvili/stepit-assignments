# პრაქტიკული დავალება: ფილმის ბილეთების ონლაინ ჯავშნის სისტემა:

# უნდა დაწეროთ პითონის სკრიპტი, რომელიც ახორციელებს კინოთეატრის ბილეთების ჯავშნის ავტომატურ შემოწმებას და დამუშავებას მომხმარებლის მიერ ერთ ხაზზე შემოტანილი ტექსტის მიხედვით.
#  მოთხოვნები და პირობები:
# მომხმარებლის ინფუთი:

# მომხმარებელს შემოჰქონდეს ტექსტი ერთ ხაზზე, მაგალითად:
# "Minda 3cali bileti, bileti ghirs 15 lari" (სადაც ფიქსირებულია 1 ბილეთის ფასი, ვთქვათ 15 ლარი).

# მონაცემების ამოღება (Parsing):

# გამოიყენეთ re.findall() მოდული, რათა ტექსტიდან ამოიღოთ რიცხვები (ბილეთების რაოდენობა და გადახდილი თანხა).

# გაითვალისწინეთ, რომ თუ მომხმარებელმა ტექსტში რიცხვი არ მიუთითა, სიები შეიძლება ცარიელი დარჩეს (IndexError რისკი).

# try - except - else - finally ბლოკის გამოყენება:

# try ბლოკში:

# გადაიყვანეთ ამოღებული რიცხვები შესაბამის ტიპებში (int ან float).

# გამოთვალეთ ჯამური ღირებულება (ბილეთების რაოდენობა * 15).

# შეამოწმეთ ლოგიკური პირობები და გამოიყენეთ raise:

# თუ ბილეთების რაოდენობა არის 0 ან უარყოფითი, ხელოვნურად აღძარით ValueError შესაბამისი შეტყობინებით ("ბილეთების რაოდენობა უნდა იყოს მინიმუმ 1").

# თუ შემოტანილი თანხა ნაკლებია ბილეთების ჯამურ ღირებულებაზე, აღძარით ZeroDivisionError ან ValueError ("თანხა არ არის საკმარისი").

# except ბლოკები (მინიმუმ ორი განსხვავებული):

# დაამუშავეთ IndexError ან ValueError (თუ ტექსტში რიცხვები ვერ მოიძებნა ან არასწორი ტიპისაა).

# დაამუშავეთ თქვენი ხელოვნურად აღძრული შეცდომები.

# else ბლოკში:

# თუ ყველაფერმა წარმატებით ჩაიარა, გამოთვალეთ მისაცემი ხურდა.

# გამოიყენეთ f-string ლამაზი დაფორმატებისთვის (მაგალითად, ხურდა დააბრუნეთ ათწილადის 2 ნიშნამდე სიზუსტით: :.2f).

# დაბეჭდეთ ჯავშნის წარმატების დასტური.

# finally ბლოკში:

# ყოველთვის (მიუხედავად იმისა, წარმატებული იყო ჯავშანი თუ შეცდომა გამოვარდა) დაბეჭდეთ ტექსტი: "[სისტემა]: ტრანზაქციის მცდელობა დასრულდა."

import re

user = input("შეიყვანე ჯავშნის ინფორმაცია: \n")
numbers = re.findall(r'\d+', user)

try:
    tickets = int(numbers[0])
    paid = float(numbers[1])

    total = tickets * 15

    if tickets <= 0:
        raise ValueError("ბილეთების რაოდენობა უნდა იყოს მინიმუმ 1")

    if paid < total:
        raise ValueError("თანხა არ არის საკმარისი")

except IndexError:
    print("შეცდომა: ტექსტში საჭირო რიცხვები ვერ მოიძებნა!")

except ValueError as e:
    print(f"შეცდომა: {e}")

else:
    change = paid - total

    print("ჯავშანი წარმატებულია!")
    print(f"ბილეთების რაოდენობა: {tickets}")
    print(f"სულ გადასახდელი: {total:.2f} ლარი")
    print(f"გადახდილი თანხა: {paid:.2f} ლარი")
    print(f"ხურდა: {change:.2f} ლარი")

finally:
    print("[სისტემა]: ტრანზაქციის მცდელობა დასრულდა.")