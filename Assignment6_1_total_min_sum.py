# შექმენი პროგრამა, რომელიც მომხმარებელს აძლევს რიცხვების შეყვანის საშუალებას.
# 'total_min_sum.py' ფაილში:

# გამოიყენე while True ციკლი. მომხმარებელს მოსთხოვე რიცხვების შეყვანა.

# თუ მომხმარებელი ჩაწერს სიტყვას "stop", ციკლი უნდა შეწყდეს (break).

# გამოიყენე try-except ბლოკი: თუ მომხმარებელი რიცხვის ნაცვლად შეიყვანს ტექსტს (გარდა "stop"-ისა), პროგრამამ არ უნდა გაითიშოს, არამედ უნდა დაბეჭდოს გაფრთხილება ("გთხოვთ შეიყვანოთ მხოლოდ რიცხვი ან 'stop'") და გააგრძელოს მუშაობა.

# ციკლის დასრულების შემდეგ (როცა მომხმარებელი წერს "stop"), პროგრამამ უნდა გამოთვალოს და დაბეჭდოს:

# შეყვანილი ვალიდური რიცხვების ჯამი (total).

# შეყვანილი რიცხვების რაოდენობა.

# მაქსიმალური და მინიმალური რიცხვი (შეგიძლია გამოიყენო max() და min() ან ციკლშივე დაიანგარიშო). მინიშნება - 
# მანამდე შექმენით min და max ცვლადები, ყოველი რიცხვის შემთხვევაში, შეყვანილი რიცხვი გადაამოწმეთ ამ ცვლადებთან და თუ მინ ზე ნაკლები იქნება, ახალი რიცხვი გახდება მინი, თუ მაქსზე მეტი იქნება, ახალი რიცხვი გახდება მაქსი.

total = 0
count = 0
minimum = None
maximum = None

while True:
    number = input("შემოიყვანეთ დასათვლელი რიცხვები (დათვლის დასასრულებლად დაწერეთ სიტყვა stop): \n")
    if number == "stop":
        break
    try:
        number = int(number)
        total += number
        count += 1
        if minimum is None or number < minimum:
            minimum = number
        if maximum is None or number > maximum:
            maximum = number
    except ValueError:
        print("გთხოვთ შეიყვანოთ მხოლოდ რიცხვი ან 'stop'")

print("Total:", total)
print("Count:", count)

if count > 0:
    print("Minimum:", minimum)
    print("Maximum:", maximum)
else:
    print("რიცხვები არ შეგიყვანიათ.")