# cart_total (რიცხვი: კალათის ღირებულება ლარებში)

# user_status (სტრიქონი: "regular", "vip", ან "admin")

# has_promo_code (ბულევანი: აქვს თუ არა აქტიური პრომოკოდი)

# loyalty_points (რიცხვი: მომხმარებლის დაგროვილი ქულები)

# delivery_city (სტრიქონი: ქალაქი, სადაც იგზავნება შეკვეთა, მაგ: "თბილისი", "ბათუმი", "რეგიონი")

# is_account_active (ბულევანი: არის თუ არა მომხმარებლის ანგარიში აქტიური/დაბლოკილი)

# ⚙️ შესასრულებელი ლოგიკური ნაბიჯები:
# ანგარიშის ვალიდაცია (Guard Clause):

# თუ მომხმარებლის ანგარიში არ არის აქტიური (is_account_active == False), სკრიპტმა დაუყოვნებლივ უნდა დაბეჭდოს შეტყობინება ("ანგარიში დაბლოკილია. შეკვეთა ვერ დამუშავდება.")

# კალათის მინიმალური ზღვარი:

# თუ კალათის ღირებულება არის 0 ან მინუსებში, გამოიტანეთ შეცდომა. თუ კალათა ცარიელია (0 ლარი), შეკვეთა არ გაატაროთ.

# ფასდაკლებების სისტემა:

# თუ მომხმარებელი არის "vip":

# მისცეს მუდმივი 20%-იანი ფასდაკლება.

# ჩაშენებული შემოწმება: თუ მას ასევე აქვს loyalty_points >= 500, დაუმატეთ დამატებითი 5%-იანი ბონუსი (სულ 25%).

# თუ მომხმარებელი არის "regular":

# ჩაშენებული შემოწმება: თუ მას აქვს has_promo_code ან მისი cart_total >= 150 ლარი, მიეცით 10%-იანი ფასდაკლება. წინააღმდეგ შემთხვევაში ფასდაკლება არ მოქმედებს (0%).

# თუ მომხმარებელი არის "admin":

# მიიღებს სრულ, 50%-იან ფასდაკლებას.

# მიტანის საფასურის გამოთვლა (in ოპერატორის გამოყენებით):

# მიტანის საფასური დამოკიდებულია ქალაქზე და კალათის საბოლოო (ფასდაკლებულ) თანხაზე:

# თუ delivery_city არის ["თბილისი", "ქუთაისი", "ბათუმი"] (გამოიყენეთ in ოპერატორი):

# თუ ფასდაკლებული თანხა მეტია ან ტოლი 100 ლარისა, მიტანა უფასოა (0 ლარი).

# სხვა შემთხვევაში მიტანა ღირს 5 ლარი.

# რეგიონებში მიტანა ფიქსირებულად ღირს 15 ლარი, მიუხედავად თანხისა.

# საბოლოო რეპორტი:

# დაბეჭდეთ დეტალური ინვოისი: კალათის საწყისი ფასი, მიღებული ფასდაკლების პროცენტი, მიტანის საფასური და საბოლოო გადასახდელი თანხა.

cart_total = float(input("კალათის ღირებულება (ლარი): "))

user_status = input("მომხმარებლის სტატუსი (regular/vip/admin): ").lower()

has_promo_code = input("აქვს პრომოკოდი? (yes/no): ").lower() == "yes"

loyalty_points = int(input("დაგროვილი ქულები: "))

delivery_city = input("მიწოდების ქალაქი: ").lower()

is_account_active = input("აქტიურია ანგარიში? (yes/no): ").lower() == "yes"

# print(cart_total,user_status,has_promo_code,loyalty_points,delivery_city,is_account_active)

discount = 0
order_valid = True

if not is_account_active :
    print("ანგარიში დაბლოკილია. შეკვეთა ვერ დამუშავდება.")
    order_valid = False

elif cart_total <= 0 :
    print("თუ კალათა ცარიელია (0 ლარი), შეკვეთა არ გატარდება")
    order_valid = False

elif user_status == "vip":
    discount = 20
    if loyalty_points >= 500:
        discount += 5
    print(f"თქვენ მოგენიჭათ VIP ფასდაკლება: {discount}%")

elif user_status == "regular":

    if has_promo_code or cart_total >= 150:
        discount = 10
        print(f"თქვენ მოგენიჭათ regular ფასდაკლება: {discount}%")

    else:
        discount = 0

elif user_status == "admin":
    discount = 50
    print(f"თქვენ მოგენიჭათ Admin ფასდაკლება: {discount}%")

else:
    print("მომხმარებლის სტატუსი არასწორია!")
    order_valid = False

if order_valid:

    discount_amount = cart_total * discount / 100

    discounted_total = cart_total - discount_amount

    if delivery_city in ["თბილისი", "ქუთაისი", "ბათუმი"] and discounted_total >= 100:
        delivery_fee = 0

    elif delivery_city in ["თბილისი", "ქუთაისი", "ბათუმი"] and discounted_total < 100:
        delivery_fee = 5

    else:
        delivery_fee = 15

    final_total = discounted_total + delivery_fee

print(f"""
================================
          YOUR INVOICE
================================
საწყისი თანხა:       {cart_total:.2f} ₾
ფასდაკლება:          {discount}%
ფასდაკლების თანხა:   {discount_amount:.2f} ₾
ფასდაკლებული თანხა:  {discounted_total:.2f} ₾
მიტანის საფასური:    {delivery_fee:.2f} ₾
--------------------------------
სულ გადასახდელი:     {final_total:.2f} ₾
================================
""")