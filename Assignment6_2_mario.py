# გამოიყენეთ try-except და while ციკლი, რომ პროგრამამ არ დაუშვას არასწორი მონაცემების შეყვანა (მაგალითად, თუ მომხმარებელი შეიყვანს ტექსტს ან 8-ზე დიდ/1-ზე პატარა რიცხვს, მოსთხოვოს თავიდან შეყვანა).


while True:
    try:
        height = int(input("შეიყვანეთ სიმაღლე (1 დან 8 ჩათვლით): "))
        if 1 <= height <= 8:
            break
        else:
            print("შეიყვანე რიცხვი 1-დან 8-ის ჩათვლით")
    except ValueError:
        print("გთხოვ, შეიყვანე მთელი რიცხვი")

for i in range(1, height + 1):
    for j in range(height - i):
        print(" ", end="")
    for k in range(i):
        print("#", end="")

    print()